// Google Books API の設定。
//
// APIキー無し(匿名)でのアクセスは、世界中の未認証リクエストが同じ小さな
// 共有割り当てを使い合う仕組みになっており、すぐに「無料枠の上限に達しました」
// (HTTP 429)になってしまう。無料の自分のAPIキーを設定すると、専用の割り当て
// (通常 1日1,000回)が使えるようになる。
//
// 取得手順(無料・クレジットカード登録不要):
// 1. https://console.cloud.google.com/ にアクセスし、Googleアカウントでログイン
// 2. 新しいプロジェクトを作成(名前は何でもよい)
// 3. 左メニュー「APIとサービス」→「ライブラリ」で "Books API" を検索して有効化
// 4. 「APIとサービス」→「認証情報」→「認証情報を作成」→「APIキー」
// 5. 作成したキーの「アプリケーションの制限」を「ウェブサイト」にし、
//    このアプリの公開URL(例: https://bop88.github.io/*)を許可リストに追加する
//    (キーの値自体はこの公開リポジトリに含まれるため、この制限が実質的な
//    アクセス制御になる。制限をかけずに使わないこと)
// 6. 生成されたキーを下の GOOGLE_BOOKS_API_KEY に貼り付けて保存・pushする
//
// 未設定(空文字のまま)でも動作するが、その場合は上記の共有の無料枠を使うため、
// 「検索に失敗しました」が頻発する可能性がある。
export const GOOGLE_BOOKS_API_KEY = "";
